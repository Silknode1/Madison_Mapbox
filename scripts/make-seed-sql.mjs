// Generate supabase/seed.sql from src/data.js:  npm run seed:sql
// data.js stays the single source of truth; the seed is an idempotent upsert you can re-run.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLACES } from '../src/data.js';

const outFile = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'seed.sql');

const q = (value) => (value == null ? 'null' : `'${String(value).replace(/'/g, "''")}'`);

const rows = PLACES.map((p, i) =>
  `  (${[
    q(p.id),
    q(p.name),
    q(p.category),
    p.lat,
    p.lng,
    q(p.address),
    q(p.description),
    q(p.warning),
    p.coordsApprox ? 'true' : 'false',
    i,
  ].join(', ')})`,
);

const sql = `-- GENERATED by scripts/make-seed-sql.mjs from src/data.js — do not edit by hand.
-- Re-generate with: npm run seed:sql   (safe to re-run: it upserts by id)

insert into public.places
  (id, name, category, lat, lng, address, description, warning, coords_approx, sort)
values
${rows.join(',\n')}
on conflict (id) do update set
  name          = excluded.name,
  category      = excluded.category,
  lat           = excluded.lat,
  lng           = excluded.lng,
  address       = excluded.address,
  description   = excluded.description,
  warning       = excluded.warning,
  coords_approx = excluded.coords_approx,
  sort          = excluded.sort,
  updated_at    = now();
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, sql);
console.log(`Wrote ${PLACES.length} places to ${outFile}`);
