// Generate supabase/seed.sql from src/data.js:  npm run seed:sql
// data.js stays the single source of truth; the seed is an idempotent upsert you can re-run.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLACES } from '../src/data.js';

const outFile = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'seed.sql');

const q = (value) => (value == null ? 'null' : `'${String(value).replace(/'/g, "''")}'`);

const rows = PLACES.map((p, i) =>
  `  (${[
    q(p.id),
    q(p.name),
    q(p.category),
    p.lat,
    p.lng,
    q(p.address),
    q(p.description),
    q(p.warning),
    p.coordsApprox ? 'true' : 'false',
    q(p.url),
    i,
  ].join(', ')})`,
);

const sql = `-- GENERATED by scripts/make-seed-sql.mjs from src/data.js — do not edit by hand.
-- Re-generate with: npm run seed:sql   (safe to re-run: it upserts by id)

insert into public.places
  (id, name, category, lat, lng, address, description, warning, coords_approx, url, sort)
values
${rows.join(',\n')}
on conflict (id) do update set
  name          = excluded.name,
  category      = excluded.category,
  lat           = excluded.lat,
  lng           = excluded.lng,
  address       = excluded.address,
  description   = excluded.description,
  warning       = excluded.warning,
  coords_approx = excluded.coords_approx,
  url           = excluded.url,
  sort          = excluded.sort,
  updated_at    = now();
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, sql);
console.log(`Wrote ${PLACES.length} places to ${outFile}`);

// One paste-able file for the Supabase SQL editor: every migration (in order) + the seed.
// Safe to re-run; on an existing database it upgrades the schema and refreshes the places.
const migrationsDir = join(dirname(outFile), 'migrations');
const migrations = readdirSync(migrationsDir).filter((f) => f.endsWith('.sql')).sort();
const setup = [
  '-- GENERATED by scripts/make-seed-sql.mjs — paste into Supabase -> SQL Editor and Run.',
  ...migrations.map((f) => `\n-- ===== ${f} =====\n${readFileSync(join(migrationsDir, f), 'utf8')}`),
  `\n-- ===== seed.sql =====\n${sql}`,
].join('\n');
const setupFile = join(dirname(outFile), 'setup.sql');
writeFileSync(setupFile, setup);
console.log(`Wrote ${migrations.length} migration(s) + seed to ${setupFile}`);
